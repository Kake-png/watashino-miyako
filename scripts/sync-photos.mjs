import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'scripts/commons-photo-manifest.json'),'utf8'));
const metadata=JSON.parse(fs.readFileSync(path.join(root,'scripts/commons-photo-metadata.generated.json'),'utf8'));
const sources={},stations={};
for(const item of manifest.filter(x=>x.include)){
 const photo=metadata[item.key];
 if(!photo||!fs.existsSync(path.join(root,'public',photo.file))||fs.statSync(path.join(root,'public',photo.file)).size===0)throw Error(`Missing photo: ${item.key}`);
 sources[item.key]=photo;(stations[item.station]??=[]).push(item.key);
}
fs.writeFileSync(path.join(root,'public/assets/photo-additions.js'),`// Generated by scripts/sync-photos.mjs from reviewed Commons photos.\nexport const PHOTO_ADDITIONS=${JSON.stringify(sources)};\nexport const STATION_PHOTO_ADDITIONS=${JSON.stringify(stations)};\n`);
console.log(`Synced ${Object.keys(sources).length} photos across ${Object.keys(stations).length} stations`);
